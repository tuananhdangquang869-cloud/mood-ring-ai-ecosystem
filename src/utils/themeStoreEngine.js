export function getAllStoreThemes() {
  const customThemes = getCustomCreatedThemes()
  return [...CURATED_STORE_THEMES, ...customThemes]
}

/**
 * Get custom user-created themes from localStorage
 */
export function getCustomCreatedThemes() {
  try {
    const saved = localStorage.getItem('mr-custom-created-themes')
    return saved ? JSON.parse(saved) : []
  } catch (e) {
    console.warn('Error reading custom created themes:', e)
    return []
  }
}

/**
 * Save a newly created custom theme
 */
export function saveCustomCreatedTheme(themeData) {
  try {
    const existing = getCustomCreatedThemes()
    const themeId = themeData.id || `custom-theme-${Date.now()}`
    const finalTheme = {
      ...themeData,
      id: themeId,
      author: themeData.author || 'Tác Giả Của Bạn',
      authorBadge: 'BẢN TỰ TẠO',
      price: 'free',
      rating: 5.0,
      ratingCount: 1,
      downloads: 1,
      isCustomUserTheme: true,
      updatedAt: new Date().toISOString()
    }

    const filtered = existing.filter(t => t.id !== themeId)
    const updated = [finalTheme, ...filtered]
    localStorage.setItem('mr-custom-created-themes', JSON.stringify(updated))
    
    // Automatically install it
    installTheme(themeId)
    
    window.dispatchEvent(new CustomEvent('mr-theme-store-updated'))
    return finalTheme
  } catch (e) {
    console.error('Error saving custom theme:', e)
    throw e
  }
}

/**
 * Delete a custom user theme
 */
export function deleteCustomCreatedTheme(themeId) {
  try {
    const existing = getCustomCreatedThemes()
    const updated = existing.filter(t => t.id !== themeId)
    localStorage.setItem('mr-custom-created-themes', JSON.stringify(updated))
    
    // If it was installed, remove it
    const installed = getInstalledThemeIds().filter(id => id !== themeId)
    localStorage.setItem('mr-installed-theme-ids', JSON.stringify(installed))

    window.dispatchEvent(new CustomEvent('mr-theme-store-updated'))
    return true
  } catch (e) {
    console.warn('Error deleting custom theme:', e)
    return false
  }
}

/**
 * Get installed theme IDs (Defaults to all curated themes)
 */
export function getInstalledThemeIds() {
  try {
    const saved = localStorage.getItem('mr-installed-theme-ids')
    if (saved) {
      return JSON.parse(saved)
    }
    // Default installed: standard curated themes
    const defaultIds = CURATED_STORE_THEMES.map(t => t.id)
    localStorage.setItem('mr-installed-theme-ids', JSON.stringify(defaultIds))
    return defaultIds
  } catch {
    return CURATED_STORE_THEMES.map(t => t.id)
  }
}

/**
 * Install a theme
 */
export function installTheme(themeId) {
  try {
    const current = getInstalledThemeIds()
    if (!current.includes(themeId)) {
      const updated = [...current, themeId]
      localStorage.setItem('mr-installed-theme-ids', JSON.stringify(updated))
      window.dispatchEvent(new CustomEvent('mr-theme-store-updated'))
    }
    return true
  } catch (e) {
    console.warn('Error installing theme:', e)
    return false
  }
}

