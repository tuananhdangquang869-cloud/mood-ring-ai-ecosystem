/**
 * Toggle favorite theme
 */
export function toggleFavoriteTheme(themeId) {
  try {
    const current = getFavoriteThemeIds()
    let updated
    if (current.includes(themeId)) {
      updated = current.filter(id => id !== themeId)
    } else {
      updated = [...current, themeId]
    }
    localStorage.setItem('mr-favorite-theme-ids', JSON.stringify(updated))
    window.dispatchEvent(new CustomEvent('mr-theme-store-updated'))
    return updated.includes(themeId)
  } catch (e) {
    console.warn('Error toggling favorite theme:', e)
    return false
  }
}

/**
 * Get the currently active theme object or ID
 */
export function getActiveThemeData() {
  try {
    const activeId = localStorage.getItem('mr-active-store-theme-id') || 'cyberpunk-neon'
    const allThemes = getAllStoreThemes()
    return allThemes.find(t => t.id === activeId) || CURATED_STORE_THEMES[0]
  } catch {
    return CURATED_STORE_THEMES[0]
  }
}

/**
 * Apply a theme to the document root and persist
 */
export function applyStoreTheme(themeOrId) {
  const theme = typeof themeOrId === 'string'
    ? getAllStoreThemes().find(t => t.id === themeOrId) || CURATED_STORE_THEMES[0]
    : themeOrId

  if (!theme) return false

  const root = document.documentElement

  // Load custom Google Font if needed
  if (theme.fontPrimary) {
    loadGoogleFontDynamically(theme.fontPrimary)
  }

  // Set CSS Variables on Root
  root.style.setProperty('--accent', theme.dominantAccent)
  root.style.setProperty('--accent-rgb', theme.accentRgb || hexToRgb(theme.dominantAccent))
  root.style.setProperty('--bg-main', theme.darkBg)
  root.style.setProperty('--card-bg', theme.cardBg)
  root.style.setProperty('--border-color', theme.borderColor)
  root.style.setProperty('--border-glow', theme.borderGlow)
  root.style.setProperty('--btn-bg', theme.btnBg)
  root.style.setProperty('--btn-hover-bg', theme.btnHoverBg)
  root.style.setProperty('--text-primary', theme.textPrimary || '#f8fafc')
  root.style.setProperty('--text-secondary', theme.textSecondary || 'rgba(248, 250, 252, 0.72)')
  
  if (theme.borderRadius) {
    root.style.setProperty('--theme-border-radius', theme.borderRadius)
  }

  if (theme.fontPrimary) {
    root.style.setProperty('--theme-font-primary', `'${theme.fontPrimary}', sans-serif`)
  }

  if (theme.bgPattern) {
    root.style.setProperty('--theme-bg-pattern', theme.bgPattern)
  }

  if (theme.bgWallpaperUrl) {
    root.style.setProperty('--theme-wallpaper-url', `url("${theme.bgWallpaperUrl}")`)
  } else {
    root.style.removeProperty('--theme-wallpaper-url')
  }

  root.setAttribute('data-store-theme', theme.id)
  root.setAttribute('data-theme', theme.id)

  localStorage.setItem('mr-active-store-theme-id', theme.id)
  localStorage.setItem('mr-theme', theme.id)

  // Ensure it is marked as installed
  installTheme(theme.id)

  window.dispatchEvent(new CustomEvent('mr-theme-applied', { detail: { theme } }))
  return true
}

/**
 * Hex to RGB helper
 */
export function hexToRgb(hex) {
  if (!hex) return '0, 240, 255'
  let c = hex.replace('#', '')
  if (c.length === 3) c = c.split('').map(x => x + x).join('')
  const num = parseInt(c, 16)
  if (isNaN(num)) return '0, 240, 255'
  return `${(num >> 16) & 255}, ${(num >> 8) & 255}, ${num & 255}`
}

